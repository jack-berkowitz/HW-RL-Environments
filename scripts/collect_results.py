#!/usr/bin/env python3
"""Collect final PPA numbers from a set of completed ORFS runs, plus any
secondary informational metrics (branch misprediction rate, cache hit
rate, etc.) a Tier2 testbench chose to report.

PPA numbers are read from the per-stage metrics JSON that ORFS writes
under <flow>/logs/<platform>/<design>/base/ -- these are properties of
the physical implementation.

Accuracy/hit-rate metrics are read from sim_logs/<tier>/<design>.log,
written by build_and_score.sh from the testbench's own simulation output.
These are NOT part of PASS/CHECK status -- per the two-tier grading
principle (functional correctness is pass/fail; prediction accuracy or
cache hit rate is informational, since there's no single "correct" value
for a legitimate design choice) they're reported alongside PPA, not
folded into it.
"""
import json
import glob
import os
import re
import sys

FLOW = os.environ.get(
    "ORFS_FLOW_DIR", "/Users/jackberkowitz/tools/OpenROAD-flow-scripts/flow"
)
PLATFORM = "sky130hd"
REPO_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def discover_designs():
    """Every design with an ORFS config, as (design_name, group) pairs.
    Sources: domains/*/design/*/orfs/ and orfs_runs/. The old
    orfs_configs/<tier>/ tree was removed with the tier layout."""
    found = []

    # Catalog-v3 tasks keep their ORFS config beside the task rather than under
    # orfs_configs/<tier>/, and there is no tier -- the domain is the useful
    # label. ORFS names its output directories after DESIGN_NICKNAME when set,
    # so that, not DESIGN_NAME, is the key the reports are found under.
    for cfg in sorted(glob.glob(os.path.join(
            REPO_DIR, "domains", "*", "design", "*", "orfs", "config.mk"))):
        domain = cfg.split(os.sep)[-5]
        nick = None
        try:
            with open(cfg) as fh:
                for line in fh:
                    line = line.strip()
                    if line.startswith("export DESIGN_NICKNAME"):
                        nick = line.split("=", 1)[1].strip()
                        break
        except OSError:
            pass
        if nick:
            found.append((nick, domain))

    # Candidate P&R runs generated by scripts/ppa_candidate.sh.
    for cfg in sorted(glob.glob(os.path.join(REPO_DIR, "orfs_runs", "*", "config.mk"))):
        found.append((os.path.basename(os.path.dirname(cfg)), "candidate"))
    return found


DISCOVERED = discover_designs()
GROUP_OF = dict(DISCOVERED)   # design -> domain / 'candidate'; no tiers any more

# --json emits the same metrics dicts as machine-readable JSON instead of the
# table. Added so find_fmax.py can read WNS/DRC/period without a second parser
# living somewhere else -- this file stays the only place ORFS metric names are
# known.
JSON_MODE = "--json" in sys.argv[1:]
ARGV = [a for a in sys.argv[1:] if a != "--json"]

if ARGV:
    # A design named explicitly that discovery did not find gets "-" rather than
    # "?": it is usually a one-off ORFS run, not a broken lookup, and a question
    # mark reads like an error.
    DESIGNS = [(d, GROUP_OF.get(d, "-")) for d in ARGV]
else:
    DESIGNS = DISCOVERED
    if not DESIGNS and not JSON_MODE:
        print(
            f"No designs found under {REPO_DIR}/orfs_configs/{PLATFORM}/"
            f"domains/*/design/*/orfs/ or orfs_runs/ "
            f"-- pass design names explicitly, or check ORFS configs exist.",
            file=sys.stderr,
        )


def load(design, stage):
    path = f"{FLOW}/logs/{PLATFORM}/{design}/base/{stage}.json"
    try:
        with open(path) as fh:
            return json.load(fh)
    except OSError:
        return {}


def period(design):
    """The clock period the run was actually constrained at, in NANOSECONDS.

    Read from the SDC that OpenROAD WRITES OUT, because that is the elaborated
    constraint -- it reflects a CLK_PERIOD_NS override, whereas the source SDC
    keeps its period behind a Tcl conditional and would always report the
    default.

    Deliberately NOT clock_period.txt. ORFS fills that file with
    `echo $(ABC_CLOCK_PERIOD_IN_PS)`, i.e. PICOSECONDS. It used to look like
    nanoseconds purely because ORFS's own extraction dropped the *1000; once the
    configs set that variable correctly the file reads 20000 for a 20 ns clock,
    and reading it as ns reports a 20 microsecond period.
    """
    base = f"{FLOW}/results/{PLATFORM}/{design}/base"
    # latest stage first: all of these are written by OpenROAD and carry a
    # literal period, unlike the copied source SDC
    for name in ("6_final.sdc", "5_route.sdc", "5_1_grt.sdc", "4_cts.sdc",
                 "3_place.sdc", "2_floorplan.sdc", "1_synth.sdc"):
        try:
            with open(os.path.join(base, name)) as fh:
                for line in fh:
                    m = re.search(r"create_clock.*?-period\s+([0-9]+\.?[0-9]*)", line)
                    if m:
                        return float(m.group(1))
        except OSError:
            continue
    return float("nan")


def sim_log_path(design, tier):
    """Find a saved simulation log for `design`, as sim_logs/<design>.log.

    The old layout was sim_logs/<tier>/<design>.log and was removed with the
    tier directories. FLAT LAYOUT NOW, and note the gap this leaves: nothing
    in the domains path currently WRITES these logs -- sim_candidate.sh prints
    METRIC lines to stdout and does not persist them. So METRIC columns stay
    empty until the submission path saves its output here. That is a known gap
    for the cross-model run, recorded rather than hidden behind a silent {}.
    """
    candidate = os.path.join(REPO_DIR, "sim_logs", f"{design}.log")
    return candidate if os.path.isfile(candidate) else None


def load_sim_metrics(design, tier):
    """Parse `METRIC: name=value` lines from the testbench's own sim
    output. Returns {} for any design whose testbench doesn't emit these
    (i.e. most modules) -- not an error, just nothing to report."""
    path = sim_log_path(design, tier)
    metrics = {}
    if not path:
        return metrics
    try:
        with open(path) as fh:
            for line in fh:
                line = line.strip()
                if not line.startswith("METRIC:"):
                    continue
                body = line[len("METRIC:"):].strip()
                if "=" not in body:
                    continue
                k, v = body.split("=", 1)
                k, v = k.strip(), v.strip()
                try:
                    metrics[k] = float(v)
                except ValueError:
                    metrics[k] = v
    except OSError:
        pass
    return metrics


rows = []
metrics_by_design = {}
for d, tier in DESIGNS:
    fin, rt, syn = load(d, "6_report"), load(d, "5_2_route"), load(d, "1_synth")
    sim_metrics = load_sim_metrics(d, tier)
    if sim_metrics:
        metrics_by_design[(d, tier)] = sim_metrics
    if not fin:
        rows.append((d, tier, None))
        continue
    rows.append(
        (
            d,
            tier,
            {
                "period": period(d),
                "wns": fin.get("finish__timing__setup__ws"),
                "tns": fin.get("finish__timing__setup__tns"),
                "hold_ws": fin.get("finish__timing__hold__ws"),
                "core_area": fin.get("finish__design__core__area"),
                "die_area": fin.get("finish__design__die__area"),
                "cell_area": fin.get("finish__design__instance__area__stdcell"),
                "insts": fin.get("finish__design__instance__count"),
                "util": fin.get("finish__design__instance__utilization"),
                "power": fin.get("finish__power__total"),
                "drc": rt.get("detailedroute__route__drc_errors"),
                "synth_cells": syn.get("synth__design__instance__count__stdcell"),
            },
        )
    )

if JSON_MODE:
    out = []
    for d, tier, m in rows:
        rec = {"design": d, "tier": tier, "completed": m is not None}
        if m is not None:
            rec.update(m)
        out.append(rec)
    print(json.dumps(out, indent=2))
    sys.exit(0)

# Column widths sized to the actual content. The old fixed <11 truncated
# nothing but ran the design and tier columns together for any name longer than
# ten characters, which every catalog-v3 nickname is
# (d_ca04_async_fifo_cdc is 21).
DW = max([len('design')] + [len(d) for d, _, _ in rows]) + 2
TW = max([len('group')]  + [len(t) for _, t, _ in rows]) + 2

hdr = (
    f"{'design':<{DW}}{'group':<{TW}}{'clk(ns)':>8}{'WNS(ns)':>9}{'TNS(ns)':>9}{'holdWNS':>9}"
    f"{'core um2':>10}{'cell um2':>10}{'insts':>7}{'util':>7}{'power(mW)':>11}"
    f"{'DRC':>5}  status"
)
print(hdr)
print("-" * len(hdr))
for d, tier, m in rows:
    if m is None:
        print(f"{d:<{DW}}{tier:<{TW}}{'--':>8}  DID NOT COMPLETE")
        continue
    ok = m["wns"] is not None and m["wns"] >= 0 and m["drc"] == 0
    print(
        f"{d:<{DW}}{tier:<{TW}}{m['period']:>8.1f}{m['wns']:>9.3f}{m['tns']:>9.3f}"
        f"{m['hold_ws']:>9.3f}{m['core_area']:>10.1f}{m['cell_area']:>10.1f}"
        f"{m['insts']:>7}{m['util']:>7.2f}{m['power'] * 1000:>11.4f}"
        f"{m['drc']:>5}  {'PASS' if ok else 'CHECK'}"
    )

if metrics_by_design:
    print()
    print("Informational metrics (not part of PASS/CHECK status):")
    for (d, tier), metrics in metrics_by_design.items():
        print(f"  {d} ({tier}):")
        for k, v in metrics.items():
            v_str = f"{v:.4f}" if isinstance(v, float) else str(v)
            print(f"    {k:<32} = {v_str}")